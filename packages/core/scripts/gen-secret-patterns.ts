/**
 * Generates `src/secret-guard/patterns.generated.ts` from the contract's secret-pattern file (B101),
 * so the service has the last good patterns compiled in and a missing file at runtime cannot
 * disable the guard. A test (`patterns.test.ts`) fails when the generated module and the contract
 * file differ.
 *
 * Usage: tsx scripts/gen-secret-patterns.ts [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, '../../../contracts/fixtures/providers/secret-patterns.json');
const TARGET = resolve(here, '../src/secret-guard/patterns.generated.ts');

interface PatternFile {
  patterns: { id: string; regex: string }[];
}

/** The text of the generated module for `file`. */
export function render(file: PatternFile): string {
  const rows = file.patterns.map(
    (p) => `  { id: ${JSON.stringify(p.id)}, regex: ${JSON.stringify(p.regex)} },`,
  );
  return [
    '// GENERATED by packages/core/scripts/gen-secret-patterns.ts (B101) from',
    '// contracts/fixtures/providers/secret-patterns.json. Do not edit; run',
    '// `pnpm --filter @centcom/core gen:secret-patterns`.',
    '',
    'export const GENERATED_PATTERNS: readonly { readonly id: string; readonly regex: string }[] = [',
    ...rows,
    '];',
    '',
  ].join('\n');
}

const file = JSON.parse(readFileSync(SOURCE, 'utf8')) as PatternFile;
const text = render(file);
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    // missing: reported below
  }
  if (current !== text) {
    process.stderr.write('patterns.generated.ts is out of date: run gen:secret-patterns\n');
    process.exit(1);
  }
} else {
  writeFileSync(TARGET, text);
  process.stdout.write(`wrote ${TARGET}\n`);
}
