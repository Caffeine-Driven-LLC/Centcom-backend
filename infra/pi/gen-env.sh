#!/usr/bin/env bash
# Writes the secrets of a new test server to a settings file (B112), once: it does nothing when the file exists, so
# running up.sh again keeps the same secrets. Every value comes from /dev/urandom; nothing is read from the
# repository, so nothing here can be a committed secret. Mode 600. The token signing key is added by up.sh with the
# image's own Node (this script needs only bash and coreutils).
#
#   infra/pi/gen-env.sh <file>       exit 0 written or already there; 2 usage
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
file="${1:?usage: gen-env.sh <settings file>}"
[[ ! -f "$file" ]] || exit 0
mkdir -p "$(dirname "$file")"
umask 077
{
  echo "# Generated by infra/pi/up.sh. Secrets for THIS test server only. Delete with reset.sh --new-secrets."
  echo "POSTGRES_PASSWORD=$(rand_hex 24)"
  echo "REDIS_PASSWORD=$(rand_hex 24)"
  echo "IDEMPOTENCY_ENCRYPTION_KEY=$(rand_b64)"
  echo "CURSOR_SIGNING_KEYS=c1:$(rand_b64url)"
  echo "OBJECT_STORE_ACCESS_KEY_ID=centcom$(rand_hex 6)"
  echo "OBJECT_STORE_SECRET_ACCESS_KEY=$(rand_hex 24)"
  echo "# Needed only with --edge tunnel (from the Cloudflare dashboard):"
  echo "CLOUDFLARE_TUNNEL_TOKEN="
} >"$file"
chmod 600 "$file"
