// @ts-check
/**
 * Writes infra/fly/fly.<service>.<env>.toml for the four services in the three environments (B091),
 * from the one source of truth for sizes and regions: infra/terraform/envs/<env>/terraform.tfvars.json.
 * Terraform creates the apps, the data layer, DNS and certificates; `fly deploy` (B092) creates the
 * machines from these files. envs.test.ts fails when a file differs from what this script renders.
 *
 *   node infra/fly/gen.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const ENVS = ['dev', 'stage', 'prod'];
export const SERVICES = ['api', 'relay', 'worker', 'admin'];

/**
 * Per service: the port it listens on, whether it takes traffic from the internet, how long a
 * stopping machine may drain, and the names of the Fly secrets it reads (values never live here;
 * infra/fly/SECRETS.md explains each name).
 */
export const SERVICE_TABLE = {
  api: {
    port: 8080,
    public: true,
    killTimeout: 30,
    secrets: [
      'DATABASE_URL',
      'REDIS_URL',
      'AUTH_SIGNING_KEYS',
      'IDEMPOTENCY_ENCRYPTION_KEY',
      'CURSOR_SIGNING_KEYS',
      'OBJECT_STORE_ACCESS_KEY_ID',
      'OBJECT_STORE_SECRET_ACCESS_KEY',
      'STRIPE_SECRET_KEY',
      'STRIPE_WEBHOOK_SECRET',
    ],
  },
  relay: {
    port: 8081,
    public: true,
    // Relays close their sockets with 1001 and jitter on SIGTERM; give them a full minute.
    killTimeout: 60,
    secrets: ['DATABASE_URL', 'REDIS_URL'],
  },
  worker: {
    port: 8082,
    public: false,
    killTimeout: 60,
    secrets: [
      'DATABASE_URL',
      'REDIS_URL',
      'OBJECT_STORE_ACCESS_KEY_ID',
      'OBJECT_STORE_SECRET_ACCESS_KEY',
      'STRIPE_SECRET_KEY',
      'STRIPE_WEBHOOK_SECRET',
      'RESEND_API_KEY',
    ],
  },
  // Private network only: no http_service, no services, so Fly gives it no public listener.
  admin: { port: 8083, public: false, killTimeout: 30, secrets: ['DATABASE_URL'] },
};

/** @param {string} env @returns {any} */
export function readVars(env) {
  const path = join(HERE, '..', 'terraform', 'envs', env, 'terraform.tfvars.json');
  return JSON.parse(readFileSync(path, 'utf8'));
}

/**
 * @param {string} env
 * @param {string} service
 * @returns {string}
 */
export function render(env, service) {
  const vars = readVars(env);
  const t = /** @type {Record<string, (typeof SERVICE_TABLE)["api"] | undefined>} */ (
    SERVICE_TABLE
  )[service];
  if (t === undefined) throw new Error(`unknown service ${service}`);
  const size = vars.machine_sizes[service];
  const base = env === 'prod' ? vars.domain : `${env}.${vars.domain}`;
  const minMachines = service === 'relay' ? size.count_per_region : size.count;
  const lines = [
    `# Generated by infra/fly/gen.mjs from infra/terraform/envs/${env}/terraform.tfvars.json. Do not edit.`,
    `# Secrets this app reads (names only, set with \`fly secrets set -a centcom-${env}-${service}\`): ${t.secrets.join(' ')}`,
    `app = "centcom-${env}-${service}"`,
    `primary_region = "${vars.region_primary}"`,
    `kill_signal = "SIGTERM"`,
    `kill_timeout = "${t.killTimeout}s"`,
    '',
    '[env]',
    `  NODE_ENV = "production"`,
    `  SERVICE_NAME = "${service}"`,
    `  HOST = "0.0.0.0"`,
    `  PORT = "${t.port}"`,
    `  LOG_LEVEL = "${env === 'dev' ? 'debug' : 'info'}"`,
    `  PUBLIC_API_URL = "https://api.${base}"`,
    '',
  ];
  if (t.public) {
    lines.push(
      '[http_service]',
      `  internal_port = ${t.port}`,
      '  force_https = true',
      '  auto_stop_machines = "off"',
      '  auto_start_machines = true',
      `  min_machines_running = ${minMachines}`,
      '',
    );
  }
  for (const [name, path] of [
    ['healthz', '/healthz'],
    ['readyz', '/readyz'],
  ]) {
    lines.push(
      `[checks.${name}]`,
      '  type = "http"',
      `  port = ${t.port}`,
      '  method = "GET"',
      `  path = "${path}"`,
      '  interval = "15s"',
      '  timeout = "5s"',
      '  grace_period = "20s"',
      '',
    );
  }
  lines.push(
    '[[vm]]',
    '  cpu_kind = "shared"',
    `  cpus = ${size.cpus}`,
    `  memory = "${size.memory_mb}mb"`,
    '',
  );
  return lines.join('\n');
}

/** @returns {Map<string, string>} file name to contents */
export function renderAll() {
  const files = new Map();
  for (const env of ENVS) {
    for (const service of SERVICES) {
      files.set(`fly.${service}.${env}.toml`, render(env, service));
    }
  }
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [name, text] of renderAll()) writeFileSync(join(HERE, name), text);
  process.stdout.write(`wrote ${SERVICES.length * ENVS.length} files\n`);
}
